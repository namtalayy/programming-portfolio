#include <stdio.h>
#include <string.h>

const char* digits[10][7] = {
    {" --- ", "|   |", "|   |", "|   |", "|   |", "|   |", " --- "},
    {"  ", "| ", "| ", "| ", "| ", "| ", "  "},
    {" --- ", "    |", "    |", " --- ", "|    ", "|    ", " --- "},
    {" --- ", "    |", "    |", " --- ", "    |", "    |", " --- "},
    {"     ", "|   |", "|   |", " --- ", "    |", "    |", "     "},
    {" --- ", "|    ", "|    ", " --- ", "    |", "    |", " --- "},
    {" --- ", "|    ", "|    ", " --- ", "|   |", "|   |", " --- "},
    {" --- ", "    |", "    |", "     ", "    |", "    |", "     "},
    {" --- ", "|   |", "|   |", " --- ", "|   |", "|   |", " --- "},
    {" --- ", "|   |", "|   |", " --- ", "    |", "    |", " --- "},
};

int main() {
    int n;
    scanf("%d", &n);

    if (n < 0 || n > 999) {
        n = 0;
    }

    char s[5];
    sprintf(s, "%d", n);
    int len = strlen(s);

    for (int row = 0; row < 7; row++) {
        for (int i = 0; i < len; i++) {
            if (i > 0) printf(" ");
            int d = s[i] - '0';
            printf("%s", digits[d][row]);
        }
        printf("\n");
    }

    return 0;
}